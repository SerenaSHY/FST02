//Primitive Data Types

//Strings: Textual data enclosed " " or ' '
let firstName = "John";
console.log("First Name:", firstName);

// Number: Represents a numberic value (30, -30, 3.14)
let age = 30;
console.log(age);
console.log("The data type of age is:", typeof age);

// Boolean: either true or false
let isAdmin = true;
console.log("Is admin:", isAdmin);
console.log("The data type of isAdmin is:", typeof isAdmin);

// Null: Intentional absence of a value
let car = null;
console.log("Car:", car);
console.log("The data type of car is:", typeof car);

//  Undedined: Unintentional absence of a value
let city; // not assigned anything, empty
console.log("City:", city);